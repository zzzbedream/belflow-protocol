// Keeps one canonical schema (prisma/schema.prisma, SQLite for local dev) and
// derives prisma/postgres/schema.prisma for hosted deployments.
//
//   node scripts/prisma-schema.mjs write     regenerate the Postgres schema
//   node scripts/prisma-schema.mjs check     exit 1 if the Postgres schema is stale
//   node scripts/prisma-schema.mjs generate  prisma generate for the target provider
//                                            (+ migrate deploy, see shouldMigrate)
//
// Target provider: postgresql when DATABASE_PROVIDER=postgresql or VERCEL=1,
// otherwise sqlite. A postgres DATABASE_URL with a sqlite target (or the
// reverse) is refused before anything is generated.
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');
export const SQLITE_SCHEMA = join(ROOT, 'prisma', 'schema.prisma');
export const POSTGRES_SCHEMA = join(ROOT, 'prisma', 'postgres', 'schema.prisma');

const HEADER = '// GENERATED by apps/web/scripts/prisma-schema.mjs from prisma/schema.prisma. Do not edit.\n\n';
const SQLITE_PROVIDER = /provider\s*=\s*"sqlite"[^\n]*/;
const CLIENT_OUTPUT = 'output   = "../apps/web/src/generated/prisma"';
const DATASOURCE_URL = 'url      = env("DATABASE_URL")';

/** Postgres variant of the canonical schema: same models, one directory deeper. */
export function toPostgresSchema(source) {
  if (!SQLITE_PROVIDER.test(source)) throw new Error('Canonical schema must use provider = "sqlite".');
  if (!source.includes(CLIENT_OUTPUT)) throw new Error(`Canonical schema must declare ${CLIENT_OUTPUT}.`);
  if (!source.includes(DATASOURCE_URL)) throw new Error(`Canonical schema must declare ${DATASOURCE_URL}.`);
  return (
    HEADER +
    source
      .replace(SQLITE_PROVIDER, 'provider = "postgresql"')
      // Migrations need a direct (non-pgbouncer) connection; the app uses the pooled URL.
      .replace(DATASOURCE_URL, `${DATASOURCE_URL}
  directUrl = env("DATABASE_URL_UNPOOLED")`)
      .replace(CLIENT_OUTPUT, 'output   = "../../apps/web/src/generated/prisma"')
  );
}

/** Which schema to build against, from the deployment environment. */
export function targetProvider(env) {
  return env.DATABASE_PROVIDER === 'postgresql' || env.VERCEL === '1' ? 'postgresql' : 'sqlite';
}

/** Rejects a DATABASE_URL whose scheme contradicts the target provider. */
export function assertUrlMatches(provider, url) {
  if (!url) {
    // A hosted build without a database would deploy an app with no tables.
    if (provider === 'postgresql') throw new Error('Target is Postgres but DATABASE_URL is not set.');
    return;
  }
  const isPostgresUrl = /^postgres(ql)?:\/\//.test(url);
  if (provider === 'sqlite' && isPostgresUrl) {
    throw new Error('DATABASE_URL is a Postgres URL but the target is SQLite. Set DATABASE_PROVIDER=postgresql.');
  }
  if (provider === 'postgresql' && !isPostgresUrl) {
    throw new Error('Target is Postgres but DATABASE_URL is not a postgres:// URL.');
  }
}

/**
 * Build-time migrations run only for Vercel Production, or when explicitly
 * enabled (BELFLOW_MIGRATE_ON_BUILD=true, e.g. a Preview with its own database),
 * so a PR preview can never migrate a shared production database.
 */
export function shouldMigrate(env) {
  if (env.BELFLOW_MIGRATE_ON_BUILD === 'true') return true;
  return env.VERCEL === '1' && env.VERCEL_ENV === 'production';
}

function writePostgresSchema() {
  mkdirSync(dirname(POSTGRES_SCHEMA), { recursive: true });
  writeFileSync(POSTGRES_SCHEMA, toPostgresSchema(readFileSync(SQLITE_SCHEMA, 'utf8')), 'utf8');
}

/** Runs the Prisma CLI with node directly: no shell, so paths with spaces stay intact. */
function prisma(args) {
  // Without a separate unpooled URL, migrations use DATABASE_URL directly.
  const env = { ...process.env, DATABASE_URL_UNPOOLED: process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL || '' };
  const cli = createRequire(import.meta.url).resolve('prisma/build/index.js');
  execFileSync(process.execPath, [cli, ...args], { stdio: 'inherit', env });
}

const MIGRATE_ATTEMPTS = 3;
const MIGRATE_RETRY_MS = 5_000;

/**
 * `migrate deploy` is idempotent, so a failed attempt is safe to repeat. On
 * Neon it can time out acquiring Prisma's advisory lock (P1002) while a
 * previous connection still holds it; a short wait usually clears it.
 */
function migrateWithRetry() {
  for (let attempt = 1; attempt <= MIGRATE_ATTEMPTS; attempt += 1) {
    try {
      prisma(['migrate', 'deploy', '--schema', POSTGRES_SCHEMA]);
      return;
    } catch (error) {
      if (attempt === MIGRATE_ATTEMPTS) throw error;
      console.warn(`[prisma-schema] migrate deploy failed (attempt ${attempt}/${MIGRATE_ATTEMPTS}); retrying in ${MIGRATE_RETRY_MS / 1000}s.`);
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, MIGRATE_RETRY_MS);
    }
  }
}

function main(command) {
  if (command === 'write') return writePostgresSchema();
  if (command === 'check') {
    const expected = toPostgresSchema(readFileSync(SQLITE_SCHEMA, 'utf8'));
    let actual = '';
    try {
      actual = readFileSync(POSTGRES_SCHEMA, 'utf8');
    } catch {
      // Missing file is stale too.
    }
    if (actual.replace(/\r\n/g, '\n') !== expected.replace(/\r\n/g, '\n')) {
      throw new Error('prisma/postgres/schema.prisma is stale. Run: node apps/web/scripts/prisma-schema.mjs write');
    }
    return;
  }
  if (command === 'generate') {
    const provider = targetProvider(process.env);
    assertUrlMatches(provider, process.env.DATABASE_URL ?? '');
    if (provider === 'sqlite') return prisma(['generate', '--schema', SQLITE_SCHEMA]);
    writePostgresSchema();
    prisma(['generate', '--schema', POSTGRES_SCHEMA]);
    if (shouldMigrate(process.env)) migrateWithRetry();
    return;
  }
  throw new Error('Usage: prisma-schema.mjs <write|check|generate>');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv[2]);
  } catch (error) {
    console.error(`[prisma-schema] ${error instanceof Error ? error.message : String(error)}`);
    process.exit(1);
  }
}
